    <h2>Why "what does it cost" doesn't have one answer</h2>
    <p>The most common question we get from new prospects is "what does commercial pool service cost?" The honest answer: between $350 and $4,000+ per month, depending on property type, pool count, complexity, frequency, and what's bundled into the contract. This guide breaks the ranges down by property type so you have a real anchor for comparing quotes.</p>
    <p>Important caveat: every quote in this guide assumes a properly bundled contract — all standard chemicals, weekly visit, photo-confirmed reporting, COI on file, dedicated account manager. Quotes that don't include those should be ~30% lower than the ranges below; that's the gap that becomes "surprise add-on bills" later.</p>

    <h2>Hotels &amp; resorts</h2>
    <p><strong>Range: $600–$2,500/month per property</strong></p>
    <p>Limited-service hotels (Hampton Inn, Holiday Inn Express, Hyatt Place) with one outdoor pool typically run $600–$1,200/month. Full-service hotels with a pool + hot tub run $1,000–$1,800/month. Resort properties (multi-pool, water features, multiple hot tubs) start at $2,000+ and scale with pool count and amenity complexity.</p>
    <p>Cost drivers specific to hotels: brand-flag QA documentation requirements (Marriott, Hilton, IHG, Choice each have specific reporting standards), dawn cleaning service window, 24/7 emergency dispatch coverage, photo report formatting for ownership review.</p>

    <h2>HOAs &amp; condos</h2>
    <p><strong>Range: $400–$1,800/month per pool</strong></p>
    <p>Single-pool HOAs (typical 25-200 unit small condo or community) run $400–$700/month. Mid-size HOAs (200-500 units, often 2 pools + hot tub) run $800–$1,400/month. Large amenity decks (500+ unit, multiple pools, water features) run $1,500–$2,500+/month. High-rise condo associations with rooftop pools have additional access-related costs (service elevator scheduling, equipment crane fees in some buildings).</p>
    <p>Cost drivers specific to HOAs: monthly board-meeting documentation, COI naming the association as additional insured, capital project capability for resurfacing/equipment cycles per the reserve study.</p>

    <h2>Multi-property portfolios</h2>
    <p><strong>Range: 8–28% volume discount off single-property pricing</strong></p>
    <p>Volume pricing is the major economic advantage of multi-property contracts. At 3-5 properties, expect 8-12% off. At 6-10 properties, 15-20%. At 11-25, 22-28%. Above 25, enterprise pricing structure with custom rate cards. Discount is on the maintenance fee — repair work and capital projects remain quoted per-occurrence.</p>
    <p>Cost drivers: dedicated account management overhead is allocated across properties (gets cheaper per property as count grows). Consolidated invoicing and per-property accounting allocation are typically included.</p>

    <h2>Fitness centers &amp; aquatic facilities</h2>
    <p><strong>Range: $700–$2,200/month per facility</strong></p>
    <p>Standard fitness center pool (lap pool only, low-mid bather load): $700–$1,200/month. Full aquatic facility (lap pool + family pool + hot tub + maybe splash pad): $1,400–$2,200/month. YMCAs and community recreation centers tend to fall in the higher range due to compliance documentation overhead.</p>
    <p>Cost drivers: high bather load drives chemistry consumption (sanitizer demand can be 3-5x a residential equivalent); FL Admin Code 64E-9 daily logging requirements; member-load chlorine targeting requires more frequent visits during peak season (often 2x weekly).</p>

    <h2>Vacation rentals</h2>
    <p><strong>Range: $250–$650/month per property</strong></p>
    <p>Single vacation home pool: $250–$400/month with weekly service. Vacation home with hot tub: $350–$500/month. Multi-property vacation rental portfolios get volume discounts (see Multi-Property section). Hot tub-only properties are typically $150-$250/month.</p>
    <p>Cost drivers: turnover-day service scheduling (between checkout and check-in) costs slightly more than fixed-day weekly service. Photo confirmation integration with property management software (Hostfully, Streamline, OwnerRez, Guesty) is typically included for managed portfolios.</p>

    <h2>Country clubs &amp; private clubs</h2>
    <p><strong>Range: $1,800–$5,000+/month for full club service</strong></p>
    <p>Private clubs typically have multiple pools — lap pool, family pool, hot tubs, sometimes a dedicated kids pool. Full-service contract for 3-5 pools runs $1,800–$3,500/month. Larger clubs with pools, splash pads, and adult-only amenities can exceed $5,000/month. The variation is driven by amenity count, not property tier — luxury clubs and mid-tier clubs pay similar per-pool rates.</p>
    <p>Cost drivers: pre-dawn service requirement, hot tub bromine specialty, lap pool clarity standards (swim-team meet-ready), event scheduling coordination, capital project planning across multi-year cycles.</p>

    <h2>Municipal &amp; school facilities</h2>
    <p><strong>Range: $900–$3,500/month per facility</strong></p>
    <p>Municipal community pool (single pool): $900–$1,500/month. K-12 school facility pool: $1,000–$1,700/month. Aquatic complex (multiple pools, university, large community center): $2,200–$3,500+/month. Billing terms accommodated to procurement office standards (net-30, net-45, or PO-based workflows).</p>
    <p>Cost drivers: RFP-formatted reporting overhead, NPDES discharge documentation, public-pool 64E-9 compliance with longer log retention requirements (24+ months), W-2 employee verification for child-safe-environment compliance at school facilities.</p>

    <h2>Water parks &amp; aquatic attractions</h2>
    <p><strong>Range: $4,000–$25,000+/month, custom-quoted</strong></p>
    <p>Water park pricing is custom-quoted per facility. Continuous chemistry monitoring (not weekly), dedicated peak-season staffing, slide and feature plumbing service, high-volume filter media swaps, and equipment redundancy planning all factor in. Most water parks operate on annual contracts with monthly invoicing.</p>

    <h2>How to compare quotes apples-to-apples</h2>
    <p>When comparing pool service quotes, normalize for these specific items. If any are missing from a quote, the quote isn't comparable to a properly bundled one:</p>
    <ul>
      <li>All standard chemicals (chlorine, stabilizer, balancers, algaecide, shock) included in monthly</li>
      <li>Same technician assigned to your property every visit</li>
      <li>COI naming your property in 24-48 hours, not 5-10 business days</li>
      <li>Same-day photo-confirmed service report (not end-of-week paper summary)</li>
      <li>Equipment failure response time committed in writing (industry standard: same business day for diagnosis)</li>
      <li>30-day cancellation, not 12+ month minimum or anniversary-only cancellation</li>
      <li>Hurricane response (debris removal, post-storm chemistry rebuild) included or clearly priced separately</li>
      <li>Annual rate increase capped (3-5% indexed to chemical cost)</li>
    </ul>

    <h2>What's <em>always</em> billed separately</h2>
    <p>Even the best commercial pool service contract bills these items separately, quoted upfront before work begins:</p>
    <ul>
      <li>Equipment repair (pumps, motors, salt cells, heaters, automation)</li>
      <li>Major filter media replacement (full DE, cartridge, or sand swap)</li>
      <li>Acid washing or surface restoration</li>
      <li>Green pool recovery treated as emergency service</li>
      <li>Leak detection (one-off scheduled service)</li>
      <li>Pool renovation, resurfacing, capital projects</li>
      <li>Drain &amp; refill (rare; quoted per project)</li>
      <li>Specialty chemicals (metal sequestrant, phosphate remover)</li>
    </ul>
