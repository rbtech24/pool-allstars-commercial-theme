    <h2>Why bother with an RFP?</h2>
    <p>Most commercial pool service vendor changes happen because nobody knew what good looked like. The HOA board fired the prior vendor for "service issues" but couldn't articulate them. Three new vendors quoted, and the board picked the cheapest. Twelve months later the same complaints are back. The RFP is how you break that cycle.</p>
    <p>A real RFP forces you to write down the standards your property requires. It forces vendors to commit, in writing, to those standards. And it gives you a comparison baseline that survives the inevitable "but their quote was lower" board meeting.</p>

    <h2>1. Define the scope (the most-skipped step)</h2>
    <p>The RFP must specify exactly what you're buying. Not "pool service" — that's how you get apples-to-oranges quotes. Specify:</p>
    <ul>
      <li><strong>Number of pools, types, and gallons.</strong> "Two pools — main pool 24,000 gal, kiddie pool 3,500 gal — both saltwater."</li>
      <li><strong>Visit frequency required.</strong> Weekly is standard for FL public pools. Confirm with your county health department.</li>
      <li><strong>What's included in the monthly price.</strong> All chemicals? Filter media? Cartridge replacement? Be explicit.</li>
      <li><strong>What's billed separately.</strong> Equipment repair, acid washing, leak detection, capital projects.</li>
      <li><strong>Reporting requirements.</strong> Daily logs? Weekly? Monthly board packet? PDF, portal, both?</li>
      <li><strong>Response time commitments.</strong> Equipment failure response (same day? next day?). Emergency response.</li>
    </ul>

    <h2>2. Set vendor qualifications upfront</h2>
    <p>Don't read 10 quotes from vendors who can't legally service a public pool. Filter at the qualification stage:</p>
    <ul>
      <li>FL business license + EIN</li>
      <li>General liability insurance — minimum $1M / $2M aggregate (verify actual policy limits, not advertised)</li>
      <li>Workers' comp insurance</li>
      <li>CPO (Certified Pool/Spa Operator) certification on every technician — Pool &amp; Hot Tub Alliance (PHTA) issued</li>
      <li>Three commercial references in your county or adjacent counties</li>
      <li>Years in business (3+ minimum, 7+ preferred for capital project capability)</li>
      <li>COI turnaround commitment (industry standard 5–10 business days; best vendors deliver in 24 hours)</li>
    </ul>

    <h2>3. Write the evaluation criteria</h2>
    <p>This is the part most RFPs fudge. Without explicit weighting, the board defaults to price. Use a 100-point scoring rubric:</p>
    <ul>
      <li><strong>Price / total cost (25 points).</strong> Lowest = full points. Apples-to-apples only — see scope.</li>
      <li><strong>Technical capability (20 points).</strong> Equipment expertise, in-house vs subcontracted, certifications.</li>
      <li><strong>Reporting &amp; compliance (15 points).</strong> Documentation quality, inspector-ready logs, board reporting format.</li>
      <li><strong>References (15 points).</strong> Verified references in similar property type. Call them.</li>
      <li><strong>Insurance &amp; risk (10 points).</strong> Coverage limits, COI turnaround, liability caps.</li>
      <li><strong>Account management (10 points).</strong> Named account manager, escalation path, communication cadence.</li>
      <li><strong>Operational scale &amp; resilience (5 points).</strong> What happens if your tech is sick? Fleet size? Backup capacity?</li>
    </ul>

    <h2>4. Required attachments from each vendor</h2>
    <ul>
      <li>Sample COI (template, not actual — the actual is delivered after contract signing)</li>
      <li>Sample monthly service report (anonymized from a current customer)</li>
      <li>Sample compliance log (FL Admin Code 64E-9 format if public pool)</li>
      <li>Three customer references with name, property type, county, and contact</li>
      <li>List of CPO-certified staff with cert numbers</li>
      <li>Standard service agreement (the contract you'll actually sign)</li>
    </ul>

    <h2>5. Timeline (typical for HOAs / hotels / fitness)</h2>
    <ul>
      <li><strong>Week 1:</strong> Issue RFP to 4–6 vendors</li>
      <li><strong>Weeks 1–3:</strong> Q&amp;A period — vendors submit clarifications</li>
      <li><strong>Week 4:</strong> Vendor responses due</li>
      <li><strong>Week 5:</strong> Internal scoring + reference calls</li>
      <li><strong>Week 6:</strong> Top 2 finalists invited for on-site walk-through</li>
      <li><strong>Week 7:</strong> Decision &amp; contract signing</li>
      <li><strong>Week 8:</strong> COI on file, transition begins</li>
    </ul>

    <h2>Bonus: questions vendors hope you won't ask</h2>
    <ul>
      <li>"Show me a service report from this exact week, last week, for one of your current customers." (Verifies they actually do same-day reporting.)</li>
      <li>"What's the longest you've had the same technician at one property?" (Verifies stable staffing.)</li>
      <li>"What percentage of your work is subcontracted vs in-house?" (Subcontracted = no warranty, slower response.)</li>
      <li>"What's your average customer tenure?" (Industry average is 2–3 years; best vendors run 5+ years.)</li>
      <li>"How do you handle a technician calling out sick?" (Real answer reveals whether they have route depth.)</li>
    </ul>

