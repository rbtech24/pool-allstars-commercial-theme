    <h2>Why verification matters for commercial properties</h2>
    <p>For a residential pool service vendor, "licensed and insured" is mostly marketing. For a commercial vendor, it\'s a procurement requirement. A board, GM, facilities director, or property manager has fiduciary duty to verify that the vendor working on the property has actual coverage if something goes wrong. The good news: every verification below is free and takes 10 minutes.</p>

    <h2>1. Florida state contractor license</h2>
    <p>Florida regulates pool service contractors through the Florida Department of Business &amp; Professional Regulation (DBPR). The license categories most relevant to commercial pool service:</p>
    <ul>
      <li><strong>Certified Pool/Spa Servicing Contractor (RP)</strong> — required to legally service commercial pools, hot tubs, and aquatic features.</li>
      <li><strong>Certified Pool/Spa Contractor (CPC)</strong> — required for new pool construction and major renovation.</li>
      <li><strong>Registered Pool/Spa Servicing Contractor (RX)</strong> — county-level registration alternative to state certification in some Florida counties.</li>
    </ul>
    <p><strong>How to verify:</strong> Visit the FL DBPR license search at myfloridalicense.com. Enter the contractor\'s name or license number. Verify status is "Active" and the license category covers commercial pool service.</p>

    <h2>2. County or local registration (if applicable)</h2>
    <p>Several Florida counties require additional county-level pool contractor registration on top of state licensing. Hillsborough, Pinellas, Pasco, Sarasota, Miami-Dade, and Broward all have specific local requirements. Confirm with your county Building Department what\'s required for commercial pool service in your specific jurisdiction.</p>

    <h2>3. General liability insurance</h2>
    <p>Industry standard for commercial pool service: <strong>$1 million per occurrence / $2 million aggregate</strong> general liability. Better vendors carry $2M / $4M.</p>
    <p><strong>How to verify:</strong> Request a sample COI before signing a contract. Confirm policy carrier is rated A- or better by AM Best. Verify your property is added as an "additional insured" on the actual issued COI after contract signing — not just promised.</p>

    <h2>4. Workers&#8217; compensation insurance</h2>
    <p>Required by Florida law for any contractor with employees. If your vendor doesn\'t carry workers\' comp and a tech is injured on your property, the property could be liable.</p>
    <p><strong>How to verify:</strong> Request workers\' comp certificate. Verify with the FL Division of Workers\' Compensation if needed.</p>

    <h2>5. CPO (Certified Pool/Spa Operator) certification</h2>
    <p>CPO is the industry standard certification for commercial pool service technicians, issued by the Pool &amp; Hot Tub Alliance (PHTA). It covers chemistry, equipment, sanitation, safety, and FL Admin Code 64E-9 compliance. Required for compliance documentation in many municipalities.</p>
    <p><strong>How to verify:</strong> Ask the vendor for CPO certification numbers for the techs who will service your property. Verify on the PHTA website. Industry leading vendors have CPO on every technician, not just one supervisor.</p>

    <h2>6. BBB accreditation &amp; rating</h2>
    <p>Better Business Bureau accreditation is voluntary but signals legitimacy. BBB rating (A+ being the highest) reflects complaint history, business practices, and tenure.</p>
    <p><strong>How to verify:</strong> Search the vendor name at bbb.org. Confirm A+ accreditation and review any unresolved complaints.</p>

    <h2>7. EIN &amp; FL business registration</h2>
    <p>Real businesses have an EIN and active Florida business registration with Sunbiz (Florida Department of State Division of Corporations).</p>
    <p><strong>How to verify:</strong> Search the vendor name on Sunbiz.org. Verify "Active" status, current officer, and business address. A vendor without active Sunbiz registration is operating outside Florida law.</p>

    <h2>8. References</h2>
    <p>Three commercial references in your county or adjacent counties. Actually call them. Industry-standard questions:</p>
    <ul>
      <li>How long has the vendor been your pool service provider?</li>
      <li>Is the same technician assigned to your property each week?</li>
      <li>Have you had any service quality issues in the past 12 months?</li>
      <li>How quickly does the vendor respond to equipment failures?</li>
      <li>Did they deliver the COI on time when the contract was signed?</li>
      <li>Would you sign with them again?</li>
    </ul>

    <h2>What to do if a vendor refuses verification</h2>
    <p>Walk away. Real commercial pool service vendors expect every item above to be verified — they\'ve been through procurement before. Vendors who push back on verification ("you can trust us") are usually missing one or more of the items.</p>

